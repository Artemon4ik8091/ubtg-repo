async def _resolve_target(event, args: str) -> str:
    """Определяет имя или обращение к адресату (из аргументов команды или из реплая)."""
    target = args.strip()
    if target:
        return target

    mention_enabled = get_config(__name__, "mention_target", True)
    if mention_enabled:
        reply_msg = await event.get_reply_message()
        if reply_msg and reply_msg.sender:
            sender = reply_msg.sender
            first_name = getattr(sender, "first_name", None) or getattr(sender, "title", None)
            if first_name:
                return first_name
            username = getattr(sender, "username", None)
            if username:
                return f"@{username}"

    return ""


def _format_compliment(compliment: str, target: str = "") -> str:
    """Форматирует комплимент с учётом префикса и адресата."""
    prefix = get_config(__name__, "prefix", "✨")
    prefix_str = f"{prefix} " if prefix else ""
    target = target.strip()

    if not target:
        return f"{prefix_str}{compliment}".strip()

    formatted_target = target if target.startswith(("@", "*", "[")) else f"**{target}**"
    first_char = compliment[0].lower() if compliment[0].isalpha() else compliment[0]
    rest = compliment[1:]

    return f"{prefix_str}{formatted_target}, {first_char}{rest}".strip()


