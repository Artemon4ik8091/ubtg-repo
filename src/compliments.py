@register_cmd("compliment", desc="Случайный комплимент. Юзай: .compliment [girl/boy/д/п] [имя]")
async def compliment_universal_cmd(client, event, args):
    args_parts = args.strip().split(maxsplit=1)
    gender_mode = None
    target_arg = ""

    if args_parts:
        first_token = args_parts[0].lower()
        if first_token in ("girl", "g", "девушка", "девушке", "д", "female", "w", "woman"):
            gender_mode = "girl"
            target_arg = args_parts[1] if len(args_parts) > 1 else ""
        elif first_token in ("boy", "b", "guy", "парень", "парню", "п", "мужчина", "мужчине", "м", "man", "male"):
            gender_mode = "boy"
            target_arg = args_parts[1] if len(args_parts) > 1 else ""
        else:
            target_arg = args.strip()

    if gender_mode == "girl":
        compliments_pool = GIRL_COMPLIMENTS
    elif gender_mode == "boy":
        compliments_pool = BOY_COMPLIMENTS
    else:
        # Если пол не указан, выбираем случайно из общего пула
        compliments_pool = GIRL_COMPLIMENTS + BOY_COMPLIMENTS

    target = await _resolve_target(event, target_arg)
    compliment = random.choice(compliments_pool)
    text = _format_compliment(compliment, target)
    await event.edit(text)
