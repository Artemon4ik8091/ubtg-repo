        for i, comp in enumerate(OLD_SERIES_COMPLIMENTS, start=1):
            await event.edit(f"❤ | {i}. {comp}")
            await asyncio.sleep(speed)

        # Финальное сообщение, указываем parse_mode="html" для корректного парсинга кастомного эмодзи
